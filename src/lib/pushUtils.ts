/**
 * Sentinel AI Browser Web Push & Device Enrollment Utilities.
 * Handles service worker registration, VAPID key conversion, PushManager subscription,
 * and server-side device association.
 */

export function urlBase64ToUint8Array(base64String: string): Uint8Array {
  const padding = '='.repeat((4 - (base64String.length % 4)) % 4);
  const base64 = (base64String + padding).replace(/-/g, '+').replace(/_/g, '/');
  const atobFn =
    typeof window !== 'undefined' && typeof window.atob === 'function'
      ? window.atob
      : (b: string) => Buffer.from(b, 'base64').toString('binary');
  const rawData = atobFn(base64);
  const outputArray = new Uint8Array(rawData.length);
  for (let i = 0; i < rawData.length; ++i) {
    outputArray[i] = rawData.charCodeAt(i);
  }
  return outputArray;
}

export async function isPushNotificationSupported(): Promise<boolean> {
  if (typeof window === 'undefined') return false;
  return Boolean(
    'serviceWorker' in navigator &&
    'PushManager' in window &&
    'Notification' in window
  );
}

export async function getExistingPushSubscription(): Promise<PushSubscription | null> {
  if (!(await isPushNotificationSupported())) return null;
  try {
    const registration = await navigator.serviceWorker.ready;
    return await registration.pushManager.getSubscription();
  } catch (err) {
    console.warn('Error fetching existing push subscription:', err);
    return null;
  }
}

export async function registerPushServiceWorker(): Promise<ServiceWorkerRegistration | null> {
  if (!(await isPushNotificationSupported())) return null;
  try {
    const registration = await navigator.serviceWorker.register('/sw.js', {
      scope: '/',
    });
    await navigator.serviceWorker.ready;
    return registration;
  } catch (err) {
    console.error('Service worker registration failed:', err);
    return null;
  }
}

export async function subscribeToWebPush(userId: string): Promise<{
  success: boolean;
  subscription?: PushSubscription;
  error?: string;
}> {
  try {
    if (!(await isPushNotificationSupported())) {
      return { success: false, error: 'Web Push is not supported in this browser.' };
    }

    // Request notification permission
    const permission = await Notification.requestPermission();
    if (permission !== 'granted') {
      return { success: false, error: 'Notification permission was denied.' };
    }

    const registration = await registerPushServiceWorker();
    if (!registration) {
      return { success: false, error: 'Could not initialize push service worker.' };
    }

    // Fetch VAPID public key
    let vapidPublicKey = process.env.NEXT_PUBLIC_VAPID_PUBLIC_KEY;
    if (!vapidPublicKey) {
      const keyRes = await fetch('/api/auth/push/vapid-public-key');
      if (keyRes.ok) {
        const keyData = await keyRes.json();
        vapidPublicKey = keyData.publicKey;
      }
    }

    if (!vapidPublicKey) {
      return { success: false, error: 'VAPID public key is not configured.' };
    }

    const convertedVapidKey = urlBase64ToUint8Array(vapidPublicKey);

    // Subscribe via PushManager
    const subscription = await registration.pushManager.subscribe({
      userVisibleOnly: true,
      applicationServerKey: convertedVapidKey as unknown as BufferSource,
    });

    const subJson = subscription.toJSON();
    if (!subJson.endpoint || !subJson.keys?.p256dh || !subJson.keys?.auth) {
      return { success: false, error: 'Incomplete push subscription generated by browser.' };
    }

    // Persist subscription on backend
    const res = await fetch('/api/auth/push/subscribe', {
      method: 'POST',
      headers: { 'Content-Type': 'application/json' },
      body: JSON.stringify({
        userId,
        subscription: {
          endpoint: subJson.endpoint,
          keys: {
            p256dh: subJson.keys.p256dh,
            auth: subJson.keys.auth,
          },
        },
        userAgent: navigator.userAgent,
      }),
    });

    if (!res.ok) {
      const err = await res.json().catch(() => ({}));
      return { success: false, error: err.detail || 'Failed to save push subscription to server.' };
    }

    return { success: true, subscription };
  } catch (err: unknown) {
    const msg = err instanceof Error ? err.message : 'Push subscription failed.';
    return { success: false, error: msg };
  }
}

export async function registerMobileDevice(
  userId: string,
  deviceName?: string
): Promise<{ success: boolean; deviceId?: string; error?: string }> {
  try {
    let deviceId = typeof window !== 'undefined' ? localStorage.getItem('sentinel_device_id') : null;
    if (!deviceId) {
      deviceId = `dev_${Math.random().toString(36).substring(2, 12)}_${Date.now()}`;
      if (typeof window !== 'undefined') {
        localStorage.setItem('sentinel_device_id', deviceId);
      }
    }

    const platform = typeof navigator !== 'undefined' ? (navigator.platform || 'Mobile') : 'Mobile';

    const res = await fetch('/api/auth/devices/register', {
      method: 'POST',
      headers: { 'Content-Type': 'application/json' },
      body: JSON.stringify({
        deviceId,
        userId,
        deviceName: deviceName || 'Registered Mobile Device',
        deviceType: 'mobile',
        platform,
      }),
    });

    if (!res.ok) {
      const err = await res.json().catch(() => ({}));
      return { success: false, error: err.detail || 'Failed to register device with server.' };
    }

    return { success: true, deviceId };
  } catch (err: unknown) {
    const msg = err instanceof Error ? err.message : 'Device registration failed.';
    return { success: false, error: msg };
  }
}
